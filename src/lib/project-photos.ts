export function getPhotoMeta(src: string, index?: number, projectName?: string): PhotoMeta {
  const normalized = src.trim();
  if (PROJECT_PHOTO_METAS[normalized]) {
    return PROJECT_PHOTO_METAS[normalized];
  }

  // Fallback if not specifically keyed
  const filename = normalized.split("/").pop() || "Screen";
  const label = filename.replace(/\.[^/.]+$/, "").replace(/[-_]/g, " ");
  return {
    src: normalized,
    title: projectName ? `${projectName} Interface` : label,
    subtitle: typeof index === "number" ? `Product walkthrough slide ${index + 1}` : "High-resolution interface walkthrough",
    tag: "Screenshot",
  };
}

